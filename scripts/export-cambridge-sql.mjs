#!/usr/bin/env node
/**
 * Export the Cambridge content as SQL, for loading into Supabase.
 *
 * The book text lives in `src/content/cambridge/*.ts` at build time only. This
 * script bundles that content, then writes a `.sql` file whose INSERT
 * statements populate `public.cambridge_tests` with it.
 *
 * Nothing it produces is committed: the output contains verbatim Cambridge
 * text and belongs in the database, not in a public git history.
 *
 * Usage:
 *   node scripts/export-cambridge-sql.mjs
 *
 * Then paste the file into Supabase → SQL Editor → Run.
 */

import { execFileSync } from 'node:child_process';
import { writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const OUT_DIR = 'supabase/generated';
const OUT_FILE = join(OUT_DIR, 'cambridge-content.sql');

execFileSync(
  './node_modules/.bin/esbuild',
  [
    'src/content/cambridge/registry.ts',
    '--bundle',
    '--format=esm',
    '--outfile=/tmp/cam-export.mjs',
    '--log-level=error',
  ],
  { stdio: 'inherit' },
);

const mod = await import(pathToFileURL('/tmp/cam-export.mjs').href);
const tests = mod.CAMBRIDGE_TESTS;

if (!Array.isArray(tests) || tests.length === 0) {
  console.error('No CAMBRIDGE_TESTS exported — nothing to do.');
  process.exit(1);
}

/**
 * Postgres string literal. Single quotes are doubled, which is the only
 * escape standard_conforming_strings needs.
 */
function lit(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

const rows = tests.map((t) => {
  const { id, book, test, module, label, source, ...rest } = t;
  const content = {
    listening: rest.listening,
    reading: rest.reading,
    writing: rest.writing,
    speaking: rest.speaking,
  };

  return `  (
    ${lit(id)},
    ${book},
    ${test},
    ${lit(module ?? 'academic')},
    ${lit(label)},
    ${lit(JSON.stringify(content))}::jsonb,
    ${lit(JSON.stringify(source))}::jsonb
  )`;
});

const sql = `-- ============================================================================
--  Cambridge book content — generated file, DO NOT COMMIT
--
--  Generated by: node scripts/export-cambridge-sql.mjs
--  Source:       src/content/cambridge/*.ts
--
--  Paste into Supabase → SQL Editor → Run. Safe to re-run: each test is
--  upserted by id, so re-running replaces the content rather than duplicating.
--
--  This file contains verbatim Cambridge text. Keep it out of git.
-- ============================================================================

insert into public.cambridge_tests (id, book, test, module, label, content, source)
values
${rows.join(',\n')}
on conflict (id) do update set
  book       = excluded.book,
  test       = excluded.test,
  module     = excluded.module,
  label      = excluded.label,
  content    = excluded.content,
  source     = excluded.source,
  updated_at = now();

-- Report what landed, so a paste that silently failed is visible.
select id, book, test, module, label,
       jsonb_array_length(content->'listening') as listening_sections,
       jsonb_array_length(content->'reading')   as reading_passages
from public.cambridge_tests
order by book desc, test;
`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT_FILE, sql, 'utf8');

const bytes = Buffer.byteLength(sql, 'utf8');
console.log(`Wrote ${OUT_FILE} — ${tests.length} test(s), ${(bytes / 1024).toFixed(1)} kB`);
for (const t of tests) console.log(`  · ${t.id}  (book ${t.book}, test ${t.test})`);
