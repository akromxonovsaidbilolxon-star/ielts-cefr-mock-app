#!/usr/bin/env node
/**
 * Scans public/audio/ and regenerates src/lib/audioManifest.ts.
 *
 *   npm run audio:manifest
 *
 * Expected file names:
 *   ielts-1.mp3 … ielts-4.mp3   IELTS listening parts
 *   ml-1.mp3   … ml-6.mp3       Multilevel listening parts
 *
 * Also prints a report of which parts still need a recording, so you can see
 * exactly what is left to produce (or have recorded by a voice artist).
 */

import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join, extname, basename } from 'node:path';

const AUDIO_DIR = 'public/audio';
const OUT = 'src/lib/audioManifest.ts';
const EXTS = new Set(['.mp3', '.m4a', '.ogg', '.wav', '.opus']);

const REQUIRED = [
  ...Array.from({ length: 4 }, (_, i) => `ielts-${i + 1}`),
  ...Array.from({ length: 6 }, (_, i) => `ml-${i + 1}`),
];

const LABELS = {
  'ielts-1': 'IELTS Part 1 — Sports centre phone call',
  'ielts-2': 'IELTS Part 2 — Wildlife park monologue',
  'ielts-3': 'IELTS Part 3 — Research project tutorial',
  'ielts-4': 'IELTS Part 4 — Urban beekeeping lecture',
  'ml-1': 'Multilevel Part 1 — Short conversations (A1)',
  'ml-2': 'Multilevel Part 2 — Swimming class call (A2)',
  'ml-3': 'Multilevel Part 3 — Weekend trip (B1)',
  'ml-4': 'Multilevel Part 4 — City park talk (B2)',
  'ml-5': 'Multilevel Part 5 — Research tutorial (B2)',
  'ml-6': 'Multilevel Part 6 — Noise lecture (C1)',
};

const found = {};

if (existsSync(AUDIO_DIR)) {
  for (const file of readdirSync(AUDIO_DIR)) {
    const ext = extname(file).toLowerCase();
    if (!EXTS.has(ext)) continue;
    const key = basename(file, ext);
    found[key] = `./audio/${file}`;
  }
}

const entries = Object.entries(found)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([key, src]) => `  '${key}': { src: '${src}' },`)
  .join('\n');

const content = `/**
 * AUTO-GENERATED by scripts/audio-manifest.mjs — do not edit by hand.
 * Run \`npm run audio:manifest\` after adding files to public/audio/.
 *
 * Files found: ${Object.keys(found).length} of ${REQUIRED.length}
 */

export type AudioKey = string;

interface AudioEntry {
  src: string;
  timestamps?: number[];
}

export const AUDIO_MANIFEST: Record<AudioKey, AudioEntry> = {
${entries || '  // (no audio files yet)'}
};

export function audioFor(key: AudioKey): AudioEntry | undefined {
  return AUDIO_MANIFEST[key];
}

export function hasRealAudio(key: AudioKey): boolean {
  return Boolean(AUDIO_MANIFEST[key]?.src);
}

export const audioKeys = {
  ielts: (partId: number): AudioKey => \`ielts-\${partId}\`,
  multilevel: (partId: number): AudioKey => \`ml-\${partId}\`,
};
`;

writeFileSync(OUT, content);

/* ---------------- report ---------------- */

console.log(`\nScanned ${AUDIO_DIR}/ — found ${Object.keys(found).length} audio file(s)\n`);

const missing = REQUIRED.filter((key) => !found[key]);
if (missing.length === 0) {
  console.log('✔ All 10 listening parts have real recordings.');
} else {
  console.log(`Still using the speech synthesiser for ${missing.length} part(s):\n`);
  for (const key of missing) {
    const label = LABELS[key] ?? key;
    const words = key.startsWith('ml') ? '~150-200 words' : '~450 words';
    console.log(`  ✘ ${key.padEnd(9)} ${label}`);
    console.log(`    ${''.padEnd(9)} needs: ${AUDIO_DIR}/${key}.mp3 (${words}, 2 speakers)`);
  }
  console.log('\nHow to produce them:');
  console.log('  1. Record with a human voice (best) — one file per part.');
  console.log('  2. Or use a neural TTS service and export MP3:');
  console.log('       ElevenLabs, Azure Speech, Google Cloud TTS, OpenAI TTS');
  console.log('     Use ONE consistent voice pair across all parts.');
  console.log(`  3. Save as ${AUDIO_DIR}/<key>.mp3, then re-run this command.\n`);
}

console.log(`Wrote ${OUT}\n`);
